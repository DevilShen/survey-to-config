def seed_runs(conn: sqlite3.Connection) -> None:
    """预生成几条推理记录。

    打开页面就能看到三条不同结局的完整链路，而不是面对一个空列表：
        001 一次通过 / 002 待补充 / 003 毛利不足转特批 / 005 快速单
    """
    from .analytics import pricing_agent as pa

    for rid in ("QR-2026-001", "QR-2026-002", "QR-2026-003", "QR-2026-005"):
        req = conn.execute("SELECT * FROM quote_requests WHERE id=?", (rid,)).fetchone()
        if req is None:
            continue
        if conn.execute("SELECT COUNT(*) c FROM quote_runs WHERE request_id=?",
                        (rid,)).fetchone()["c"]:
            continue
        res = pa.run(conn, dict(req), as_of=date(2026, 10, 18))
        pa.persist(conn, dict(req), res, "周敏")
